#!/bin/bash
set -euo pipefail

# docker-entrypoint.sh - Entry point for the Ta Cukrárna Docker test container
# Starts Apache in the foreground and configures the environment for Playwright E2E tests.

# Ensure the document root directory exists
mkdir -p /var/www/html

# Copy any runtime state that should survive (these are excluded from rsync --delete)
# The opening-hours.jsonc is already copied in the Dockerfile, but ensure it exists
if [ ! -f /var/www/html/opening-hours.jsonc ]; then
    echo '{"schedule":[],"exceptions":[]}' > /var/www/html/opening-hours.jsonc
fi

# Ensure the API directory exists
mkdir -p /var/www/html/api

# Seed the SQLite test database (idempotent): schema + one signable passkey
# whose credentials land in /var/www/html/api/DB/test-credentials.json
echo "🌱 Seeding SQLite test database..."
if ! php /usr/local/bin/seed-passkeys.php; then
    echo "⚠️  Seeding failed - admin sign-in tests will not work"
fi

# Apache (www-data) must be able to write the DB dir (SQLite WAL) and the
# docroot (atomic tmp+rename of opening-hours.jsonc) - mirrors the VPS
# group-write setup from DEVELOPMENT_TOOLS.md
chown -R www-data:www-data /var/www/html/api/DB || true

# Configure the external MTA (msmtp) from the container .env's SMTP_* vars.
# PHP's mb_send_mail() uses the system sendmail (msmtp-mta provides the
# /usr/sbin/sendmail symlink), which relays through the configured smart
# host - so registration e-mails really reach the mailbox. Without SMTP_HOST
# no config is written and mail sending fails as usual (logged).
configure_mta() {
    local env_file="/var/www/.env"
    [ -r "$env_file" ] || return 0

    # env KEY=VALUE -> strip optional surrounding quotes
    env_get() {
        local value
        value=$(sed -n "s/^$1\s*=\s*//p" "$env_file" | head -1)
        value="${value%\"}"
        value="${value#\"}"
        value="${value%\'}"
        value="${value#\'}"
        printf '%s' "$value"
    }

    local host port user pass from
    host=$(env_get SMTP_HOST)
    [ -n "$host" ] || return 0
    port=$(env_get SMTP_PORT)
    user=$(env_get SMTP_USER)
    pass=$(env_get SMTP_PASS)
    from=$(env_get SMTP_FROM | sed 's/.*<\(.*\)>.*/\1/')
    [ -n "$from" ] || from="$user"

    cat > /etc/msmtprc <<EOF
# Generated by docker-entrypoint.sh from the container .env - do not edit
defaults
auth           on
tls            on
tls_trust_file /etc/ssl/certs/ca-certificates.crt
syslog         mail

account        default
host           $host
port           ${port:-587}
from           $from
user           $user
password       $pass
EOF
    chown root:www-data /etc/msmtprc
    chmod 640 /etc/msmtprc
    echo "📧 msmtp configured for $host:${port:-587}"
}
configure_mta

# Remind how to register (the token is regenerated at every container start;
# stale ones are removed - the URL below is always the current one)
CRED_FILE=/var/www/html/api/DB/test-credentials.json
if [ -r "$CRED_FILE" ]; then
    REGISTER_URL=$(sed -n 's/.*"registerUrl":"\([^"]*\)".*/\1/p' "$CRED_FILE" | head -1 | sed 's/\\\//\//g')
    if [ -n "$REGISTER_URL" ]; then
        echo ""
        echo "➡️  Admin registration: $REGISTER_URL"
        echo "➡️  Admin sign-in:      http://localhost/admin/"
    fi
fi

# Start Apache in the foreground
# Apache serves the docroot /var/www/html: the Next.js static export (out/
# contents) with the PHP API at /api/ and opening-hours.jsonc at the root -
# the same layout as the production VPS.
echo "🚀 Starting Apache..."
exec apache2ctl -D FOREGROUND